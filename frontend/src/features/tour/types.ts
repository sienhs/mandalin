import type { ReactElement } from 'react'

/**
 * 오버레이 안내(스포트라이트 투어)의 자료형.
 *
 * <p>기존 `OnboardingTour` 는 화면 한가운데 뜨는 <b>설명 팝업</b>이라 "이 서비스가 무엇인가"
 * 까지만 말할 수 있었다. 여기는 <b>실제 화면 요소를 가리키는</b> 안내라 "이 버튼이 무엇을
 * 하는가" 를 말한다. 둘은 겹치지 않으므로 나란히 둔다 — 팝업이 먼저 끝난 뒤 이쪽이 뜬다.
 */
/**
 * 안내가 있는 화면.
 *
 * <p>리포트에는 두지 않는다 — 그 화면은 결과를 읽는 곳이라 조작할 것이 "다시 분석하기"
 * 하나뿐이고, 무엇을 해 주는 기능인지는 <b>홈 안내의 한 단계</b>(`nav-report`)로 이미
 * 소개한다. 화면마다 안내를 하나씩 두면 목록만 길어진다.
 *
 * <p>`welcome` 만 화면이 아니라 <b>때</b>다 — 설명 팝업이 끝나는 그 순간 한 장만 뜨는
 * 이음매라, 도움말 목록(`TOUR_ORDER`)에는 넣지 않는다. 다시 볼 것이 아니라 지나가는 안내다.
 *
 * <p>`village` 는 다른 화면과 성격이 다르다 — 본문이 <b>3D 캔버스</b>라 눌러야 할 것이
 * DOM 이 아니라 그림 안에 있다. 그래서 안내가 가리키는 것은 캔버스 전체와 그 위/아래에
 * 얹힌 조작 UI 뿐이고, "블록을 누르면" 같은 말은 글로 대신한다.
 */
export type TourId = 'welcome' | 'home' | 'editor' | 'coach' | 'village'

export type TourStep = {
  /**
   * 가리킬 요소의 `data-tour` 값. <b>없으면 화면 가운데 카드로 뜬다</b>(들머리·맺음말).
   *
   * <p>찾지 못해도 안내가 끊기지 않는다 — 화면 폭이나 데이터 상태에 따라 없는 요소가
   * 생기기 때문이다(사이드바는 좁은 화면에서 사라지고, 만다라트가 없으면 홈이 빈 화면이다).
   * 그때는 가운데 카드로 물러난다.
   */
  target?: string
  title: string
  body: string
  /** 카드 아래 한 줄. 지금 눌러야 할 것이나 주의할 점을 적는다. */
  hint?: string
  /**
   * 강조한 요소를 <b>실제로 누를 수 있게</b> 한다.
   *
   * <p>평소에는 화면 전체를 투명한 판으로 덮어 오조작을 막는다(안내 도중에 과제가 완료되면
   * 안 된다). 이 값이 참인 단계에서만 구멍을 뚫고, 그 요소를 누르면 다음 단계로 넘어간다.
   */
  interactive?: boolean
  /** 마무리 단계에 붙이는 이동 버튼. 누르면 안내가 끝나고 그 화면으로 간다. */
  action?: { label: string; to: string; state?: unknown }
  /**
   * 표적이 <b>지금 화면에 없으면 이 단계를 아예 뺀다</b>(안내를 시작하는 시점에 판정).
   *
   * <p>화면에 있는 것이 데이터에 따라 달라지는 자리에 쓴다 — 만다라트가 하나도 없는 홈에는
   * 요약·할 일·마을 카드가 없고, 리포트를 아직 안 만들었으면 결과 칸이 없다. 그때 가운데
   * 카드로 물러나면 <b>화면에 없는 것을 설명하는</b> 안내가 되어 오히려 헷갈린다.
   *
   * <p>안내 도중에 <b>생기는</b> 자리에는 쓰면 안 된다(코치의 제안 카드는 예시 대화가 끝나야
   * 나타난다) — 시작 시점에는 없으므로 통째로 빠져 버린다.
   */
  requireTarget?: boolean
  /** 강조 테두리 색. AI 가 하는 일은 청록으로 갈라 둔다(`ActionButton` 의 `ai` 와 같은 뜻). */
  tone?: 'brand' | 'ai'
  /** 구멍 여백. 기본 8px. 큰 카드를 가리킬 때만 줄인다. */
  padding?: number
}

export type Tour = {
  id: TourId
  /**
   * 도움말 목록에 뜨는 이름. <b>목록에 있는 글자는 이것뿐이다</b> — 한 줄 설명을 곁들이면
   * 고르기 전에 읽을 것이 생기는데, 어차피 눌러야 알 수 있는 내용이라 목록만 길어졌다.
   */
  label: string
  /**
   * 목록의 아이콘. <b>이 앱이 이미 쓰고 있는 것을 그대로 쓴다</b>(`components/common/Icons`).
   *
   * <p>유니코드 이모지를 쓰면 안 된다 — 글꼴이 기기마다 달라 윈도우·맥·안드로이드에서 색과
   * 굵기가 제각각이고, 바로 옆 사이드바의 선 아이콘과 나란히 놓이면 둘이 다른 디자인처럼
   * 보인다. 사이드바가 "홈 · 내 만다라트 · 리포트" 에 쓰는 바로 그 아이콘을 여기서도 쓰면
   * 어느 화면 안내인지 글자를 읽기 전에 짝이 맞는다.
   */
  icon: (props: { className?: string }) => ReactElement
  /** 이 안내가 도는 화면. 다른 곳에서 시작하면 여기로 옮긴 뒤 뜬다. */
  path: string
  steps: TourStep[]
}
